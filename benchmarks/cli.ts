import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { parseArgs } from 'node:util';
import { runTrial, scenarios, summarize, type Mode, type Trial } from './local';

const { values } = parseArgs({
  options: {
    repetitions: { type: 'string', default: '3' },
    output: { type: 'string', default: '.ravel/benchmarks' },
  },
});
const repetitions = Number(values.repetitions);
if (!Number.isSafeInteger(repetitions) || repetitions < 1 || repetitions > 100)
  throw new Error('--repetitions must be an integer between 1 and 100.');
const directory = resolve(
  values.output,
  new Date().toISOString().replaceAll(':', '-') + '-' + process.pid,
);
mkdirSync(directory, { recursive: true });
console.log('Ravel local synthetic benchmark (not an official AsynCodeBench score)');
console.log('Six scenarios; identical scripted generators; OFF, Observe, and Guard.');
const trials: Trial[] = [];
// One excluded warmup per mode. Rotate measurement order to reduce fixed-order bias.
const modes: Mode[] = ['off', 'observe', 'guard'];
for (const mode of modes) await runTrial(scenarios[0], mode, join(directory, 'warmup', mode), 0);
for (let repetition = 1; repetition <= repetitions; repetition++) {
  for (let index = 0; index < scenarios.length; index++) {
    const scenario = scenarios[index];
    for (let offset = 0; offset < modes.length; offset++) {
      const mode = modes[(repetition + index + offset) % modes.length];
      trials.push(
        await runTrial(
          scenario,
          mode,
          join(directory, `${repetition}-${scenario.id}-${mode}`),
          repetition,
        ),
      );
    }
  }
  console.log(`Completed repetition ${repetition}/${repetitions}`);
}
const summary = summarize(trials);
const meanElapsed = (mode: Mode) => {
  const selected = trials.filter((trial) => trial.mode === mode);
  return selected.reduce((sum, trial) => sum + trial.elapsedMs, 0) / selected.length;
};
const offMean = meanElapsed('off');
const runtimeOverhead = (['observe', 'guard'] as const).map((mode) => ({
  mode,
  meanExtraMsPerTrial: meanElapsed(mode) - offMean,
  meanRuntimeRatioToOff: offMean > 0 ? meanElapsed(mode) / offMean : null,
}));
let commit: string | null = null;
let workingTreeDirty: boolean | null = null;
try {
  commit = execFileSync('git', ['rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
  workingTreeDirty = Boolean(
    execFileSync('git', ['status', '--porcelain'], { encoding: 'utf8' }).trim(),
  );
} catch {
  /* Source archives may not have Git metadata. */
}
const regressions = trials.filter((trial) => {
  const scenario = scenarios.find((item) => item.id === trial.scenario)!;
  return (
    trial.success !== (trial.mode === 'guard' || !scenario.stale) ||
    trial.writesRejected !== Number(trial.mode === 'guard' && scenario.stale) ||
    (trial.mode === 'observe' && trial.hazardsDetected !== Number(scenario.stale))
  );
});
const report = {
  schemaVersion: 1,
  suite: 'ravel-local-synthetic',
  officialAsynCodeBench: false,
  createdAt: new Date().toISOString(),
  commit,
  workingTreeDirty,
  node: process.version,
  platform: process.platform,
  repetitions,
  warmupTrialsExcluded: modes.length,
  model: null,
  tokens: null,
  tokenOverhead: null,
  tokenNote: 'Scripted generators make no model calls; token overhead is not measured.',
  timingNote:
    'Includes runtime setup, SQLite facts/projections, and materialization; excludes fixture setup and evaluation. Tiny local workloads do not estimate model-heavy benchmark overhead.',
  scenarios,
  summary,
  runtimeOverhead,
  regressions: regressions.map(({ scenario, mode, repetition }) => ({
    scenario,
    mode,
    repetition,
  })),
  trials,
};
writeFileSync(join(directory, 'report.json'), JSON.stringify(report, null, 2) + '\n');
const rows = summary.map(
  (item) =>
    `| ${item.mode} | ${item.trials} | ${(item.successRate * 100).toFixed(1)}% | ${(item.dependencyPassRate * 100).toFixed(1)}% | ${item.hazardsDetected ?? 'unmeasured'} | ${item.writesRejected} | ${item.attemptsRerun} | ${item.medianElapsedMs.toFixed(2)} |`,
);
const markdown = `# Ravel local synthetic benchmark\n\nNot an official AsynCodeBench result. No models or API keys were used.\n\n| Mode | Trials | Success | Dependency pass | Hazards | Rejections | Retries | Median ms |\n| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |\n${rows.join('\n')}\n\n${report.timingNote}\n\nTokens: not measured. See report.json for scenarios, individual trials, generation counts, generated bytes, and trace directories. Warmup trials are excluded.\n\nRegression mismatches: ${regressions.length}.\n`;
writeFileSync(join(directory, 'report.md'), markdown);
console.log(markdown);
console.log(`Saved results and traces: ${directory}`);
if (regressions.length) process.exitCode = 1;
